import { createRequire } from 'node:module';
import type { Terminal as HeadlessTerminal } from '@xterm/headless';
import type { SerializeAddon as TerminalSerializer } from '@xterm/addon-serialize';
import { ParserTail } from './parserTail.js';

const require = createRequire(import.meta.url);
const { Terminal } = require('@xterm/headless') as typeof import('@xterm/headless');
const { SerializeAddon } = require('@xterm/addon-serialize') as typeof import('@xterm/addon-serialize');
const { Unicode11Addon } = require('@xterm/addon-unicode11') as typeof import('@xterm/addon-unicode11');

export type SnapshotCursor = { offset: number; sequence: number };
export type TerminalSnapshotCapture = SnapshotCursor & {
  data: Buffer;
  cols: number;
  rows: number;
};

export type TerminalSnapshotOptions = {
  cols: number;
  rows: number;
  /** Receives only responses generated by the live headless parser. */
  onResponse?: (data: string) => void;
  /** Called once when an ordered snapshot operation or publisher callback fails. */
  onFailure?: (error: unknown) => void;
};

function checkedSize(value: number, name: string): number {
  if (!Number.isInteger(value) || value < 1 || value > 500) throw new Error(`Invalid terminal ${name}`);
  return value;
}

/**
 * Maintains a canonical headless xterm screen for the bytes sent through a tmux
 * display client. Writes, resizes, and captures share one ordered barrier so a
 * capture describes exactly the output prefix identified by its cursor.
 */
export class TerminalSnapshot {
  private readonly terminal: HeadlessTerminal;
  private readonly serializer: TerminalSerializer;
  private readonly parserTail = new ParserTail();
  private readonly responseDisposable: { dispose(): void };
  private queue: Promise<void> = Promise.resolve();
  private failure: unknown;
  private readonly onFailure?: (error: unknown) => void;
  private disposed = false;
  private offset = 0;
  private sequence = 0;
  private cols: number;
  private rows: number;

  constructor(options: TerminalSnapshotOptions) {
    this.cols = checkedSize(options.cols, 'columns');
    this.rows = checkedSize(options.rows, 'rows');
    this.onFailure = options.onFailure;
    this.terminal = new Terminal({ cols: this.cols, rows: this.rows, allowProposedApi: true });
    const unicode11 = new Unicode11Addon();
    this.terminal.loadAddon(unicode11);
    this.terminal.unicode.activeVersion = '11';
    this.serializer = new SerializeAddon();
    this.terminal.loadAddon(this.serializer);
    const disposable = this.terminal.onData((data) => options.onResponse?.(data));
    this.responseDisposable = disposable;
  }

  /**
   * Enqueues one output chunk and returns the cursor after that chunk. The
   * optional callback runs after xterm has consumed the bytes, making it safe
   * for callers to publish the same chunk only after this point.
   */
  write(data: Buffer, callback?: () => void): SnapshotCursor {
    this.assertOpen();
    if (!Buffer.isBuffer(data)) throw new TypeError('Terminal output must be a Buffer');
    if (!Number.isSafeInteger(this.offset + data.byteLength)) throw new Error('Terminal output offset overflow');
    const chunk = Buffer.from(data);
    this.offset += chunk.byteLength;
    const cursor = this.nextCursor();
    void this.enqueue(() => new Promise<void>((resolve, reject) => {
      this.parserTail.push(chunk);
      try {
        this.terminal.write(chunk, () => {
          try {
            callback?.();
            resolve();
          } catch (error) {
            reject(error);
          }
        });
      } catch (error) {
        reject(error);
      }
    })).catch(() => undefined);
    return cursor;
  }

  /** Enqueues a display resize in the same sequence as output. */
  resize(cols: number, rows: number, callback?: () => void): SnapshotCursor {
    this.assertOpen();
    const nextCols = checkedSize(cols, 'columns');
    const nextRows = checkedSize(rows, 'rows');
    const cursor = this.nextCursor();
    void this.enqueue(() => {
      this.terminal.resize(nextCols, nextRows);
      this.cols = nextCols;
      this.rows = nextRows;
      callback?.();
    }).catch(() => undefined);
    return cursor;
  }

  /** Returns a serialized screen plus any incomplete UTF-8/control sequence. */
  capture(): Promise<TerminalSnapshotCapture> {
    if (this.disposed) return Promise.reject(new Error('Terminal snapshot is disposed'));
    if (this.failure !== undefined) return Promise.reject(this.failure);
    const cursor = { offset: this.offset, sequence: this.sequence };
    return this.enqueue(() => {
      const screen = Buffer.from(this.serializer.serialize(), 'utf8');
      const tail = Buffer.from(this.parserTail.snapshot(), 'base64');
      return {
        data: Buffer.concat([screen, tail]),
        ...cursor,
        cols: this.cols,
        rows: this.rows,
      };
    });
  }

  /** Stops accepting operations and disposes xterm after queued work drains. */
  async dispose(): Promise<void> {
    if (this.disposed) return;
    this.disposed = true;
    await this.queue;
    this.responseDisposable.dispose();
    this.terminal.dispose();
  }

  private nextCursor(): SnapshotCursor {
    if (!Number.isSafeInteger(this.sequence + 1)) throw new Error('Terminal sequence overflow');
    this.sequence++;
    return { offset: this.offset, sequence: this.sequence };
  }

  private enqueue<T>(action: () => T | Promise<T>): Promise<T> {
    const operation = this.queue.then(() => {
      if (this.failure !== undefined) throw this.failure;
      return action();
    });
    this.queue = operation.then(() => undefined, (error) => {
      if (this.failure !== undefined) return;
      this.failure = error;
      try { this.onFailure?.(error); } catch { /* Failure reporting must not reject the queue. */ }
    });
    return operation;
  }

  private assertOpen(): void {
    if (this.disposed) throw new Error('Terminal snapshot is disposed');
    if (this.failure !== undefined) throw this.failure;
  }
}
